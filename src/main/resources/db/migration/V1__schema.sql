CREATE TABLE artista (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(200) NOT NULL,
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('CANTOR', 'BANDA'))
);
CREATE TABLE album (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL
);
CREATE TABLE artista_album (
    album_id BIGINT NOT NULL REFERENCES album(id),
    artista_id BIGINT NOT NULL REFERENCES artista(id),
    PRIMARY KEY (album_id, artista_id)
);
CREATE TABLE capa_album (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id BIGINT NOT NULL REFERENCES album(id),
    chave_objeto VARCHAR(255) NOT NULL UNIQUE
);
CREATE TABLE regional (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_externo INTEGER NOT NULL,
    nome VARCHAR(200) NOT NULL,
    ativo BOOLEAN NOT NULL
);
CREATE UNIQUE INDEX regional_externo_ativo_idx ON regional (codigo_externo) WHERE ativo = TRUE;

